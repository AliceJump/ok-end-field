REGION_CONFIG_NAME = "Daily Region Config"
REGION_CONFIG_MODE_KEY = "使用独立地区配置"
REGION_SCOPE_MODE_KEY = "地区范围模式"
REGION_SCOPE_AREAS_KEY = "地区列表"

REGION_SCOPE_EXCLUDE = "排除所选地区"
REGION_SCOPE_INCLUDE = "仅执行所选地区"
REGION_SCOPE_MODES = [REGION_SCOPE_EXCLUDE, REGION_SCOPE_INCLUDE]

DEFAULT_REGION_CONFIG = {
    REGION_SCOPE_MODE_KEY: REGION_SCOPE_EXCLUDE,
    REGION_SCOPE_AREAS_KEY: [],
}

REGION_CONFIG_DESCRIPTION = {
    REGION_SCOPE_MODE_KEY: (
        "「排除所选地区」会执行当前及未来新增的全部地区，但跳过列表中的地区；「仅执行所选地区」只执行列表中的地区。"
    ),
    REGION_SCOPE_AREAS_KEY: "选择要排除或仅执行的地区；地区列表由当前主数据自动生成。",
}

REGION_CONFIG_TYPE = {
    REGION_SCOPE_MODE_KEY: {
        "type": "drop_down",
        "options": REGION_SCOPE_MODES,
    },
    REGION_SCOPE_AREAS_KEY: {
        "type": "multi_selection",
        "options": list(areas_list),
    },
}

region_config_option = ConfigOption(
    REGION_CONFIG_NAME,
    DEFAULT_REGION_CONFIG,
    description="全局地区执行范围",
    config_description=REGION_CONFIG_DESCRIPTION,
    config_type=REGION_CONFIG_TYPE,
    icon=Icons.Navigation,
)

_REGION_CONFIG: Config | None = None
_MIGRATION_BACKUP_VERSION = "v1"
_REPAIR_VERSION = "trade_only_v2"
_SCOPE_KEYS = (REGION_CONFIG_MODE_KEY, REGION_SCOPE_MODE_KEY, REGION_SCOPE_AREAS_KEY)


def get_region_config() -> Config:
    """Return the persisted global region configuration."""
    global _REGION_CONFIG
    if _REGION_CONFIG is None:
        _REGION_CONFIG = Config(REGION_CONFIG_NAME, DEFAULT_REGION_CONFIG)
    return _REGION_CONFIG


def resolve_region_areas(
    mode: str,
    selected_areas: Iterable[str] | None,
    available_areas: Iterable[str] | None = None,
) -> list[str]:
    """Resolve a stable ordered region list from include/exclude semantics."""
    available = list(areas_list if available_areas is None else available_areas)
    selected = {str(area) for area in (selected_areas or [])}
    if mode == REGION_SCOPE_INCLUDE:
        return [area for area in available if area in selected]
    return [area for area in available if area not in selected]


def _backup_file_once(source_path: str, backup_name: str, version: str = _MIGRATION_BACKUP_VERSION) -> None:
    source = Path(source_path)
    if not source.is_file():
        return
    backup_dir = Path(config_path("region_scope_migration_backup", version))
    backup_dir.mkdir(parents=True, exist_ok=True)
    target = backup_dir / backup_name
    if not target.exists():
        shutil.copy2(source, target)


def _repair_region_segment(segment: dict, original: dict, legacy_areas: Iterable[str]) -> bool:
    """Undo only the scope generated by v1, preserving explicit scope edits."""
    if any(key in original for key in _SCOPE_KEYS):
        return False
    original_flags = {area: original[area] for area in legacy_areas if isinstance(original.get(area), bool)}
    disabled = [area for area, enabled in original_flags.items() if not enabled]
    if not disabled or any(segment.get(area) is not True for area in original_flags):
        return False
    if (
        segment.get(REGION_CONFIG_MODE_KEY) is not True
        or segment.get(REGION_SCOPE_MODE_KEY) != REGION_SCOPE_EXCLUDE
        or segment.get(REGION_SCOPE_AREAS_KEY) != disabled
    ):
        return False

    segment.update(original_flags)
    for key in _SCOPE_KEYS:
        segment.pop(key, None)
    return True


def migrate_legacy_region_scope(task_class_name: str, legacy_areas: Iterable[str] | None = None) -> None:
    """Keep legacy trade flags; repair v1's broader exclusions once from backup."""
    marker = config_path("region_scope_migration_backup", _REPAIR_VERSION, f"{task_class_name}.done.json")
    if Path(marker).is_file():
        return
    legacy_areas = list(areas_list if legacy_areas is None else legacy_areas)
    backup_dir = Path(config_path("region_scope_migration_backup", _MIGRATION_BACKUP_VERSION))
    task_path = config_path(f"{task_class_name}.json")
    data = read_json_file(task_path)
    original = read_json_file(str(backup_dir / f"{task_class_name}.json"))
    if isinstance(data, dict) and isinstance(original, dict) and _repair_region_segment(data, original, legacy_areas):
        _backup_file_once(task_path, f"{task_class_name}.json", _REPAIR_VERSION)
        write_json_file(task_path, data)

    from src.tasks.account.account_scope_store import get_store_path, update_overrides

    override_path = get_store_path()
    original_overrides = read_json_file(str(backup_dir / Path(override_path).name))
    original_accounts = original_overrides.get("accounts", {}) if isinstance(original_overrides, dict) else {}

    def apply(store):
        accounts = store.get("accounts") or {}
        if not isinstance(accounts, dict):
            return store
        for account_id, task_map in accounts.items():
            if not isinstance(task_map, dict):
                continue
            segment = task_map.get(task_class_name)
            original_tasks = original_accounts.get(account_id)
            if original_tasks is None:
                # v1 backed up username-keyed stores before update_overrides
                # normalized their account keys into persistent IDs.
                registry = store.get("account_registry") or {}
                account_meta = registry.get(account_id, {}) if isinstance(registry, dict) else {}
                username = account_meta.get("username") if isinstance(account_meta, dict) else None
                original_tasks = original_accounts.get(username, {}) if isinstance(username, str) else {}
            original_segment = original_tasks.get(task_class_name) if isinstance(original_tasks, dict) else None
            if (
                isinstance(segment, dict)
                and isinstance(original_segment, dict)
                and _repair_region_segment(segment, original_segment, legacy_areas)
            ):
                _backup_file_once(override_path, Path(override_path).name, _REPAIR_VERSION)
        return store

    if isinstance(original_accounts, dict) and original_accounts:
        update_overrides(apply)
    write_json_file(marker, {"completed": True})
